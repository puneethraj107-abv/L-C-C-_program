#include <iostream>
using namespace std;

int main() {
    double a ,b;
    cout<<"enter the number a = ";
    cin>>a;
    cout<<"enter the number b = ";
    cin>>b;
    cout<<"sum = "<<(a+b)<<"\n";
    cout<<"difference = "<<(a-b)<<"\n";
    cout<<"multiplication = "<<(a*b)<<"\n";
    cout<<"division = "<<(a/b)<<"\n";
    cout<<"pre-incerment operator "<<(++a)<<"\n";
    cout<<"pre-decrement operator "<<(--a)<<"\n";
    return 0;
}
